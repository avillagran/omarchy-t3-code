#!/usr/bin/env node
// Scoped source intake; this does not advance the repository's global nightly pin.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),{stripTypeScriptTypes}=require('node:module');
const revision='32a0531748c44b25072d7495ce0b9bd7e9450a87';
const digest='9c7aa34d4b110777c896f412be1f4eff6c60f08d39fe9b3bae2ad69f22f45754';
function build(nativeRoot) {
 const source=fs.readFileSync(path.join(nativeRoot,'apps/desktop/src/preview/CdpRelay.ts'),'utf8');
 if(crypto.createHash('sha256').update(source).digest('hex')!==digest)throw Error('Pinned native CDP source mismatch');
 const js=stripTypeScriptTypes(source,{mode:'strip'});
 const declaration='export function createCdpRelayConnection(';
 if(js.split(declaration).length!==2)throw Error('Unexpected native CDP factory shape');
 return '// T3 Code '+revision+'; MIT, licenses/T3-Code-MIT.txt.\n// Generated by tools/build-native-cdp.cjs; preserve native algorithms.\n(()=>{\n'+js.replace(declaration,'function createCdpRelayConnection(')+'\nglobalThis.__o3CreateCdpRelayConnection=createCdpRelayConnection;\n})();\n';
}
module.exports={build,revision,digest};
if(require.main===module) {
 if(process.argv.length!==4)throw Error('Usage: build-native-cdp.cjs NATIVE_ROOT OUTPUT_FILE');
 fs.writeFileSync(process.argv[3],build(process.argv[2]));
}
