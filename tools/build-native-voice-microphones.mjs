// Build-only extraction of the complete original microphone metadata function.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {stripTypeScriptTypes} from 'node:module';
import {fileURLToPath} from 'node:url';
if(!fs.existsSync('/run/.containerenv')||process.versions.node!=='26.13.0')
 throw Error('Private pinned build runtime required');
const [native]=process.argv.slice(2);
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const revision='83a3674ffd84ffb33de768210c806cb1ac53fd80';
const source='apps/web/src/speech/browserMicrophones.ts';
const sourceSha256='ae9e0733b8eea7942943139bd3c1e47f271feaeb750d86918df3fe4206b65c54';
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const bytes=fs.readFileSync(path.join(native,source));
if(hash(bytes)!==sourceSha256)throw Error('Changed original microphone source');
const compiled=stripTypeScriptTypes(bytes.toString(),{mode:'strip'}).trim();
const output='// Original T3 Code '+revision+'. MIT; licenses/T3-Code-MIT.txt.\n'+
 '// Generated by tools/build-native-voice-microphones.mjs; TypeScript types only removed.\n'+compiled+'\n';
fs.writeFileSync(path.join(root,'ui/voice/browser-microphones.mjs'),output);
fs.writeFileSync(path.join(root,'ui/voice/browser-microphones.sources.json'),JSON.stringify({
 revision,source,sourceSha256,node:process.versions.node,outputSha256:hash(output),
 adaptations:['Complete original module; TypeScript types only removed'],
 scope:'Read-only audioinput metadata enumeration; never requests microphone permission or opens an audio stream',
},null,2)+'\n');
console.log(JSON.stringify({bytes:Buffer.byteLength(output),sourceSha256,outputSha256:hash(output)}));
