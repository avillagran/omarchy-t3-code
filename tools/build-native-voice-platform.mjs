// Build-only linkage of the complete original browser voice platform. Runtime
// capture/transport dependencies are explicit host adapters, never globals.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire, stripTypeScriptTypes} from 'node:module';
import {fileURLToPath, pathToFileURL} from 'node:url';
if (!fs.existsSync('/run/.containerenv') || process.versions.node !== '26.13.0')
  throw Error('Private pinned build runtime required');
const [native,compiler] = process.argv.slice(2);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const revision = '83a3674ffd84ffb33de768210c806cb1ac53fd80';
const sourceFiles = {
  'apps/web/src/speech/browserVoiceInput.ts':'6e06aa3b3211720a175378383a487adad2058431e3429bc1c2c5b4aa6ec6bb73',
  'packages/shared/src/speech.ts':'af32fbbc5e6028bb6ef0c652a1ed26163da61034c1b4330a54093d749f7c9523',
};
const hash = value => crypto.createHash('sha256').update(value).digest('hex');
if (fs.readFileSync(path.join(native,'REVISION'),'utf8').trim() !== revision)
  throw Error('Native source revision changed');
const lock = fs.readFileSync(path.join(root,'tools/voice-compiler/package-lock.json'));
if (hash(lock) !== hash(fs.readFileSync(path.join(compiler,'package-lock.json'))))
  throw Error('Compiler lock changed');
const require = createRequire(path.join(compiler,'package.json'));
const Babel = await import(pathToFileURL(require.resolve('@babel/core')).href);
const plugins = await Promise.all([
  '@babel/plugin-transform-async-to-generator',
  '@babel/plugin-transform-class-properties',
  '@babel/plugin-transform-optional-catch-binding',
].map(async name => (await import(pathToFileURL(require.resolve(name)).href)).default));
const declarations=[];
const selected=[];
for (const [name,digest] of Object.entries(sourceFiles).reverse()) {
  const bytes=fs.readFileSync(path.join(native,name));
  if (hash(bytes)!==digest) throw Error('Changed original platform source');
  const parsed=Babel.parseSync(stripTypeScriptTypes(bytes.toString(),{mode:'strip'}),
    {sourceType:'module',configFile:false,babelrc:false});
  for(const statement of parsed.program.body) {
    if(statement.type==='ImportDeclaration')continue;
    const declaration=statement.type==='ExportNamedDeclaration'?statement.declaration:statement;
    if(!declaration)throw Error('Unexpected platform export');
    const names=declaration.type==='VariableDeclaration'
      ?declaration.declarations.map(value=>value.id.name):[declaration.id?.name];
    const wanted=name.endsWith('/speech.ts')
      ?names.some(value=>['cloudSpeechLanguages','effectiveSpeechLanguage'].includes(value)):true;
    if(wanted){declarations.push(declaration);selected.push({source:name,names});}
  }
}
if(JSON.stringify(selected.map(value=>value.names).flat().sort()) !==
    JSON.stringify(['cloudSpeechLanguages','effectiveSpeechLanguage',
      'isVoiceTranscriptionError','createBrowserVoiceInputPlatform'].sort()))
  throw Error('Complete original platform declarations required');
const program=Babel.parseSync('',{sourceType:'script',configFile:false,babelrc:false});
program.program.body=declarations;
const compiled=Babel.transformFromAstSync(program,null,
  {sourceType:'script',configFile:false,babelrc:false,comments:true,plugins}).code;
const dependencies=['Schema','VoiceTranscriptionError','requireCloudSpeechKey',
  'transcribeCloudPcm','getEnvironmentSpeechStatus','getEnvironmentSpeechStreamUrl',
  'openSpeechStream','throwIfVoiceTranscriptionAborted','transcribeEnvironmentPcm',
  'createBrowserPcmCapture','runEnvironmentSpeech','fetch','Uint8Array'];
const linkage=dependencies.map(name=>`var ${name}=platform.${name};`).join('\n');
const output='.pragma library\n// Original T3 Code '+revision+'. MIT; licenses/T3-Code-MIT.txt.\n'+
  '// Babel helpers: MIT; licenses/Babel-helpers-MIT.txt.\n'+
  '// Generated by tools/build-native-voice-platform.mjs. Build-only Node/Babel.\n'+
  'function create(platform){\n'+linkage+'\n'+compiled+'\n'+
  'return {createBrowserVoiceInputPlatform:createBrowserVoiceInputPlatform,'+
  'effectiveSpeechLanguage:effectiveSpeechLanguage,cloudSpeechLanguages:cloudSpeechLanguages};\n}\n';
fs.writeFileSync(path.join(root,'ui/js/NativeVoiceInput.js'),output);
fs.writeFileSync(path.join(root,'ui/js/NativeVoiceInput.sources.json'),JSON.stringify({
  revision,sourceFiles,selected,compilerLockSha256:hash(lock),node:process.versions.node,
  outputSha256:hash(output),dependencies,
  adaptations:['Whole original declarations retained; TypeScript/import/export linkage only',
    'Standard Babel async/class/optional-catch transforms for Qt',
    'Host capture and shared SDK runtime dependencies supplied explicitly'],
  scope:'Original platform factory and language selection; host adapters and production UI activation require separate acceptance',
},null,2)+'\n');
console.log(JSON.stringify({bytes:Buffer.byteLength(output),declarations:selected.length}));
