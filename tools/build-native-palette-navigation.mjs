// Generate the original pure palette navigation declarations for Qt's JS engine.
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {createRequire, stripTypeScriptTypes} from 'node:module';
import {pathToFileURL} from 'node:url';

if (!fs.existsSync('/run/.containerenv') || process.versions.node !== '26.13.0')
  throw Error('Private pinned generation runtime required');
const [original, compiler, output] = process.argv.slice(2);
if (!original || !compiler || !output) throw Error('Expected original source, compiler and output');
const sha = value => createHash('sha256').update(value).digest('hex');
const source = fs.readFileSync(original);
const sourceSha256 = '68f65fa1b148c5c2fc64ac7f3bb3681283c60d6f877374a49b902976c9ebd5c1';
if (sha(source) !== sourceSha256) throw Error('Original palette source changed');
const require = createRequire(path.join(compiler, 'package.json'));
const Babel = await import(pathToFileURL(require.resolve('@babel/core')).href);
const spread = (await import(pathToFileURL(require.resolve('@babel/plugin-transform-object-rest-spread')).href)).default;
const options = {sourceType:'module', configFile:false, babelrc:false};
const originalAst = Babel.parseSync(stripTypeScriptTypes(source.toString(), {mode:'strip'}), options);
const names = ['createCommandPaletteSearchState', 'reduceCommandPaletteSearchState',
  'getCommandPaletteMode', 'getCommandPaletteInputPlaceholder'];
const body = originalAst.program.body.flatMap(node => {
  const declaration = node.type === 'ExportNamedDeclaration' ? node.declaration : node;
  return declaration?.type === 'FunctionDeclaration' && names.includes(declaration.id.name)
    ? [declaration] : [];
});
if (body.length !== names.length || names.some(name => !body.some(node => node.id.name === name)))
  throw Error('Original complete navigation declarations unavailable');
const ast = Babel.parseSync('', {...options, sourceType:'script'});
ast.program.body = body;
// Qt also lacks Array.prototype.at. Supply its standard coercion/bounds
// semantics, leaving the original reducer's control flow and state intact.
const at = Babel.parseSync(`function _nativeArrayAt(value,index) {
  if(value===null||value===void 0)throw new TypeError('Invalid Array.at receiver');
  var object=Object(value),number=+object.length;
  var length=number!==number||number<=0?0:Math.min(Math.floor(number),9007199254740991);
  var relative=+index;
  var integer=relative!==relative||relative===0?0:relative<0?Math.ceil(relative):Math.floor(relative);
  var key=integer>=0?integer:length+integer;
  return key<0||key>=length?void 0:object[key];
}`, {...options, sourceType:'script'}).program.body;
let atCalls = 0;
Babel.traverse(ast, {CallExpression(site) {
  const callee=site.node.callee;
  if(callee.type!=='MemberExpression'||callee.computed||callee.property.name!=='at')return;
  if(site.node.arguments.length!==1)throw Error('Unexpected original Array.at call');
  site.replaceWith(Babel.types.callExpression(Babel.types.identifier('_nativeArrayAt'),[callee.object,...site.node.arguments]));
  atCalls++;
}});
if(atCalls!==1)throw Error('Original navigation Array.at closure changed');
ast.program.body.unshift(...at);
// Qt's parser lacks object spread. Preserve the declarations through the same
// standard Babel lowering already used by the other native Qt helpers.
const generated = Babel.transformFromAstSync(ast, null, {...options, sourceType:'script', comments:true, plugins:[spread]}).code;
const unbound = new Set();
const intrinsics = new Set(['Object','Symbol','String','Number','Math','TypeError']);
Babel.traverse(Babel.parseSync(generated, {...options, sourceType:'script'}), {
  ReferencedIdentifier(site) {
    if (site.node.name === 'arguments' && site.findParent(parent => parent.isFunction() && !parent.isArrowFunctionExpression())) return;
    if (!site.scope.getBinding(site.node.name) && !intrinsics.has(site.node.name)) unbound.add(site.node.name);
  },
});
if (unbound.size) throw Error('Unlinked navigation dependencies: '+[...unbound].join(','));
const code = '.pragma library\n\n// Original T3 Code ade473018d32003658b7d38693e083ee2e314bd8.\n' +
  '// MIT; licenses/T3-Code-MIT.txt. Generated by tools/build-native-palette-navigation.mjs.\n' + generated + '\n';
fs.mkdirSync(output, {recursive:true});
fs.writeFileSync(path.join(output, 'NativePaletteNavigation.js'), code, {flag:'wx'});
fs.writeFileSync(path.join(output, 'NativePaletteNavigation.sources.json'), JSON.stringify({
  revision:'ade473018d32003658b7d38693e083ee2e314bd8',
  sourcePath:'apps/web/src/components/CommandPalette.logic.ts', sourceSha256,
  declarations:names, outputSha256:sha(code), node:process.versions.node,
  compilerLockSha256:sha(fs.readFileSync(path.join(compiler,'package-lock.json'))),
  adaptations:['TypeScript erasure, export removal and standard Babel object-spread lowering for Qt; standard Array.at coercion/bounds polyfill; complete original declarations and closure verification'],
}, null, 2)+'\n', {flag:'wx'});
console.log('NATIVE_PALETTE_NAVIGATION_GENERATED '+JSON.stringify({bytes:Buffer.byteLength(code), declarations:names.length}));
