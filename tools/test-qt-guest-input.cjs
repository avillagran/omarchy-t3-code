'use strict';
const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const scope = {};
vm.runInNewContext(fs.readFileSync(process.argv[2], 'utf8'), scope);
(async () => {
    const calls = [], gates = [], failures = [];
    let focused = false;
    const adapter = scope.T3QtGuestInput.create((method, params) => {
        calls.push({method, params});
        return new Promise((resolve, reject) => gates.push({resolve, reject}));
    }, () => ({activeFocus: focused, url: 'owned', title: 'owned', userAgent: 'actual'}), code => failures.push(code));
    assert.equal(adapter.webContents.focusedFrame, undefined);
    focused = true;
    assert.ok(adapter.webContents.focusedFrame);
    adapter.webContents.sendInputEvent({type: 'rawKeyDown', keyCode: 'Left', modifiers: ['shift']});
    adapter.webContents.sendInputEvent({type: 'char', keyCode: '😀', modifiers: []});
    const barrier = adapter.sendCommand('Runtime.evaluate', {expression: 'value'});
    await new Promise(setImmediate);
    assert.equal(calls.length, 1);
    assert.equal(calls[0].params.key, 'ArrowLeft');
    assert.equal(calls[0].params.modifiers, 8);
    gates.shift().resolve({});
    await new Promise(setImmediate);
    assert.equal(calls.length, 2);
    assert.equal(calls[1].params.text, '😀');
    gates.shift().resolve({});
    await new Promise(setImmediate);
    assert.equal(calls[2].method, 'Runtime.evaluate');
    gates.shift().resolve({value: 'done'});
    await barrier;
    adapter.webContents.sendInputEvent({type: 'keyUp', keyCode: 'Enter', modifiers: []});
    await new Promise(setImmediate);
    gates.shift().reject(Error('synthetic transport failure'));
    await new Promise(setImmediate);
    await assert.rejects(adapter.sendCommand('Runtime.evaluate', {}), /synthetic transport failure/);
    assert.deepEqual(failures, ['private_browser_input_failed']);
    adapter.close();
    await assert.rejects(adapter.sendCommand('Runtime.evaluate', {}), /private_browser_closed/);
    assert.equal(calls.length, 4);
    console.log('QT_GUEST_INPUT_BOUNDARY_PASS: real-focus snapshot, Unicode/arrows, ACK ordering, failure retirement, closed admission');
})().catch(error => { console.error(error); process.exitCode = 1; });
